import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

const files = {
  "/products/light-powder.svg": "public/products/light-powder.svg",
  "/products/packaging.svg": "public/products/packaging.svg",
  "/products/bronzer-powder.svg": "public/products/bronzer-powder.svg",
  "/products/deep-powder.svg": "public/products/deep-powder.svg",
};

let body = "";
for (const [urlKey, rel] of Object.entries(files)) {
  let s = fs.readFileSync(path.join(root, rel), "utf8");
  if (urlKey === "/products/packaging.svg") {
    s = s.replace('CREAM " POWDER', "CREAM · POWDER");
  }
  body += `  ${JSON.stringify(urlKey)}: ${JSON.stringify(s)},\n`;
}

const out = `/** Auto-generated by scripts/embed-catalog-svgs.mjs — inlined SVG so images always render. */\nexport const CATALOG_SVG_MARKUP: Record<string, string> = {\n${body}};\n`;
fs.writeFileSync(path.join(root, "src/lib/catalogSvgMarkup.ts"), out, "utf8");
console.log("Wrote src/lib/catalogSvgMarkup.ts");

/**
 * Solid swatch JPEGs + TS hex map for UI fallbacks.
 *
 * Uses filtered pixel averages (skips near-white glare / near-black crush), then
 * a makeup-style finish: deeper luminance + stronger saturation so swatches read
 * clearly as complexion product tones.
 *
 * Outputs:
 *   public/products/swatches/{tone}-{cream|powder}.jpg
 *   src/lib/toneSwatches.generated.ts
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const productsDir = path.join(root, "public", "products");
const outDir = path.join(productsDir, "swatches");
const tsOut = path.join(root, "src", "lib", "toneSwatches.generated.ts");

const TONES = ["light", "bronzer", "deep"];

async function main() {
  let sharp;
  try {
    sharp = (await import("sharp")).default;
  } catch {
    console.error("Missing dependency: sharp. Run: npm install");
    process.exit(1);
  }

  fs.mkdirSync(outDir, { recursive: true });

  /** @type {Record<string, { cream: string; powder: string }>} */
  const hexMap = {};

  for (const tone of TONES) {
    const creamPath = path.join(productsDir, `${tone}-cream.jpg`);
    const powderPath = path.join(productsDir, `${tone}-powder.jpg`);
    if (!fs.existsSync(creamPath)) {
      console.warn(`Skip ${tone}: missing ${tone}-cream.jpg`);
      continue;
    }

    let creamRgb;
    let powderRgb;

    if (fs.existsSync(powderPath)) {
      creamRgb = await midtoneMeanFromFile(sharp, creamPath);
      powderRgb = await midtoneMeanFromFile(sharp, powderPath);
    } else {
      const split = await splitCreamPowderFromDuo(sharp, creamPath);
      creamRgb = split.creamRgb;
      powderRgb = split.powderRgb;
    }

    const separated = separateIfTooClose(creamRgb, powderRgb, 22);
    creamRgb = makeupFinishRgb(separated.a, "cream", tone);
    powderRgb = makeupFinishRgb(separated.b, "powder", tone);

    await writeSwatch(sharp, path.join(outDir, `${tone}-cream.jpg`), creamRgb);
    await writeSwatch(sharp, path.join(outDir, `${tone}-powder.jpg`), powderRgb);

    hexMap[tone] = {
      cream: rgbToHex(creamRgb),
      powder: rgbToHex(powderRgb),
    };
    console.log(`Wrote swatches for ${tone}`);
  }

  const ts = `/* eslint-disable */\n// Auto-generated by npm run swatches. Do not edit by hand.\nexport const TONE_SWATCH_HEX = ${JSON.stringify(hexMap, null, 2)} as const;\n`;
  fs.writeFileSync(tsOut, ts, "utf8");
  console.log("Wrote", path.relative(root, tsOut));
}

async function midtoneMeanFromFile(sharp, filePath) {
  return midtoneMeanFromPipeline(sharp(filePath).rotate());
}

async function midtoneMeanFromPipeline(pipeline) {
  const { data, info } = await pipeline
    .clone()
    .resize(160, 160, { fit: "inside" })
    .removeAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  const ch = info.channels;
  let rs = 0,
    gs = 0,
    bs = 0,
    n = 0;
  const push = (r, g, b, lo, hi) => {
    const L = rgbLuma01(r, g, b);
    const s = sat01(r, g, b);
    if (L < lo || L > hi) return;
    // drop near-neutral background (large white table)
    if (L > 0.86 && s < 0.08) return;
    rs += r;
    gs += g;
    bs += b;
    n += 1;
  };

  for (let i = 0; i < data.length; i += ch) {
    push(data[i], data[i + 1], data[i + 2], 0.05, 0.96);
  }
  if (n < 120) {
    rs = gs = bs = n = 0;
    for (let i = 0; i < data.length; i += ch) {
      push(data[i], data[i + 1], data[i + 2], 0.02, 0.99);
    }
  }
  if (n === 0) {
    const buf = await pipeline.clone().resize(1, 1, { fit: "fill" }).removeAlpha().raw().toBuffer();
    return [buf[0], buf[1], buf[2]];
  }
  return [rs / n, gs / n, bs / n];
}

async function splitCreamPowderFromDuo(sharp, filePath) {
  const meta = await sharp(filePath).rotate().metadata();
  const w = meta.width ?? 1;
  const h = meta.height ?? 1;
  const gutter = Math.max(2, Math.round(Math.min(w, h) * 0.04));

  const useHorizontalSplit = w >= h * 1.05;
  /** @type {import("sharp").Sharp[]} */
  const pipelines = [];
  if (useHorizontalSplit) {
    const mid = Math.floor(w / 2);
    const lw = Math.max(1, mid - gutter);
    const rw = Math.max(1, w - mid - gutter);
    pipelines.push(sharp(filePath).rotate().extract({ left: 0, top: 0, width: lw, height: h }));
    pipelines.push(
      sharp(filePath).rotate().extract({ left: mid + gutter, top: 0, width: rw, height: h }),
    );
  } else {
    const mid = Math.floor(h / 2);
    const th = Math.max(1, mid - gutter);
    const bh = Math.max(1, h - mid - gutter);
    pipelines.push(sharp(filePath).rotate().extract({ left: 0, top: 0, width: w, height: th }));
    pipelines.push(
      sharp(filePath).rotate().extract({ left: 0, top: mid + gutter, width: w, height: bh }),
    );
  }

  const scored = [];
  for (const p of pipelines) {
    const rgb = await midtoneMeanFromPipeline(p);
    const stats = await p.clone().stats();
    const texture =
      (stats.channels[0].stdev + stats.channels[1].stdev + stats.channels[2].stdev) / 3;
    const chroma = labChroma(rgb[0], rgb[1], rgb[2]);
    const sat = sat01(rgb[0], rgb[1], rgb[2]);
    scored.push({ rgb, texture, chroma, sat });
  }

  const [a, b] = scored;
  // Cream: richer color (higher chroma / saturation). Powder: more muted.
  let cream = a.chroma >= b.chroma ? a : b;
  let powder = a.chroma >= b.chroma ? b : a;
  if (Math.abs(a.chroma - b.chroma) < 1.2) {
    cream = a.sat >= b.sat ? a : b;
    powder = a.sat >= b.sat ? b : a;
  }
  if (Math.abs(a.sat - b.sat) < 0.02) {
    cream = a.texture >= b.texture ? a : b;
    powder = a.texture >= b.texture ? b : a;
  }

  return { creamRgb: cream.rgb, powderRgb: powder.rgb };
}

/**
 * Powder: skin-toned (muted warmth, complexion-like).
 * Cream: sculpt + blush (more pigment, contour depth + flush).
 */
function makeupFinishRgb(rgb, part, tone) {
  let [h, s, l] = rgbToHsl(rgb[0], rgb[1], rgb[2]);

  if (part === "powder") {
    const skinHue = tone === "deep" ? 0.045 : tone === "bronzer" ? 0.072 : 0.095;
    h = lerpHue(h, skinHue, 0.58);
    s = clamp(s * 0.52 + 0.06, 0.08, 0.36);
    l = clamp(l * 0.9 + 0.05, 0.28, 0.52);
  } else {
    let sculptHue;
    let blushHue;
    let sculptBlushMix;
    let satMul;
    let satCap;
    if (tone === "light") {
      // Soft bronze contour + dusty rose blush (not lipstick red)
      sculptHue = 0.065;
      blushHue = 0.94;
      sculptBlushMix = 0.45;
      satMul = 1.22;
      satCap = 0.62;
    } else if (tone === "bronzer") {
      sculptHue = 0.045;
      blushHue = 0.02;
      sculptBlushMix = 0.4;
      satMul = 1.48;
      satCap = 0.9;
    } else {
      sculptHue = 0.985;
      blushHue = 0.96;
      sculptBlushMix = 0.42;
      satMul = 1.42;
      satCap = 0.88;
    }
    const sculptBlush = lerpHue(sculptHue, blushHue, sculptBlushMix);
    h = lerpHue(h, sculptBlush, 0.52);
    s = clamp(s * satMul + 0.06, 0.32, satCap);
    l = clamp(l * 0.62, 0.11, 0.42);
  }

  return hslToRgb(h, s, l);
}

function lerpHue(h0, h1, t) {
  let d = h1 - h0;
  if (d > 0.5) d -= 1;
  if (d < -0.5) d += 1;
  let h = h0 + d * t;
  if (h < 0) h += 1;
  if (h > 1) h -= 1;
  return h;
}

function rgbToHsl(r, g, b) {
  const R = r / 255;
  const G = g / 255;
  const B = b / 255;
  const max = Math.max(R, G, B);
  const min = Math.min(R, G, B);
  const d = max - min;
  let h = 0;
  const l = (max + min) / 2;
  let s = 0;
  if (d > 1e-6) {
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    switch (max) {
      case R:
        h = ((G - B) / d + (G < B ? 6 : 0)) / 6;
        break;
      case G:
        h = ((B - R) / d + 2) / 6;
        break;
      default:
        h = ((R - G) / d + 4) / 6;
        break;
    }
  }
  return [h, s, l];
}

function hslToRgb(h, s, l) {
  if (s <= 0) {
    const v = clampByte(l * 255);
    return [v, v, v];
  }
  const q = l < 0.5 ? l * (1 + s) : l + s - l * s;
  const p = 2 * l - q;
  const t = (x) => {
    if (x < 0) x += 1;
    if (x > 1) x -= 1;
    if (x < 1 / 6) return p + (q - p) * 6 * x;
    if (x < 0.5) return q;
    if (x < 2 / 3) return p + (q - p) * (2 / 3 - x) * 6;
    return p;
  };
  return [clampByte(t(h + 1 / 3) * 255), clampByte(t(h) * 255), clampByte(t(h - 1 / 3) * 255)];
}

function clamp(n, lo, hi) {
  return Math.max(lo, Math.min(hi, n));
}

function separateIfTooClose(a, b, minDist) {
  const d = Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2]);
  if (d >= minDist) return { a, b };
  // Push powder slightly darker / less chromatic in Lab-ish way (simple RGB nudge)
  const p = [clampByte(b[0] * 0.88), clampByte(b[1] * 0.86), clampByte(b[2] * 0.9)];
  const c = [clampByte(a[0] * 1.02), clampByte(a[1] * 0.99), clampByte(a[2] * 0.97)];
  return { a: c, b: p };
}

async function writeSwatch(sharp, outPath, [r, g, b]) {
  await sharp({
    create: {
      width: 640,
      height: 640,
      channels: 3,
      background: { r: clampByte(r), g: clampByte(g), b: clampByte(b) },
    },
  })
    .jpeg({ quality: 92, mozjpeg: true })
    .toFile(outPath);
}

function rgbLuma01(r, g, b) {
  return (0.299 * r + 0.587 * g + 0.114 * b) / 255;
}

function sat01(r, g, b) {
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  return max === 0 ? 0 : (max - min) / max;
}

function clampByte(n) {
  return Math.max(0, Math.min(255, Math.round(n)));
}

function rgbToHex([r, g, b]) {
  return `#${[r, g, b].map((x) => clampByte(x).toString(16).padStart(2, "0")).join("")}`;
}

function labChroma(r, g, b) {
  const [, a, b2] = rgbToLab(r, g, b);
  return Math.hypot(a, b2);
}

function rgbToLab(r, g, b) {
  let R = r / 255;
  let G = g / 255;
  let B = b / 255;
  R = R > 0.04045 ? ((R + 0.055) / 1.055) ** 2.4 : R / 12.92;
  G = G > 0.04045 ? ((G + 0.055) / 1.055) ** 2.4 : G / 12.92;
  B = B > 0.04045 ? ((B + 0.055) / 1.055) ** 2.4 : B / 12.92;
  let X = (R * 0.4124564 + G * 0.3575761 + B * 0.1804375) / 0.95047;
  let Y = (R * 0.2126729 + G * 0.7151522 + B * 0.072175) / 1.0;
  let Z = (R * 0.0193339 + G * 0.119192 + B * 0.9503041) / 1.08883;
  X = X > 0.008856 ? X ** (1 / 3) : 7.787 * X + 16 / 116;
  Y = Y > 0.008856 ? Y ** (1 / 3) : 7.787 * Y + 16 / 116;
  Z = Z > 0.008856 ? Z ** (1 / 3) : 7.787 * Z + 16 / 116;
  const L = 116 * Y - 16;
  const a = 500 * (X - Y);
  const b2 = 200 * (Y - Z);
  return [L, a, b2];
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
